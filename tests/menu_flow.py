"""Menus (1.6.3, like Facebook): bottom tab bar + ☰ Menu page on phones/tablets, side menu on wide screens, floating windows, info pages, pharmacist accounts.
Run:  python3 tests/menu_flow.py      (needs Playwright; uses the fake Supabase in tests/fake_supabase.js)
Prints PASS/FAIL lines and writes screenshots to tests/shots/."""
import json, os, sys
from playwright.sync_api import sync_playwright
exec(open('tests/owner_flow.py').read().split('with sync_playwright()')[0])   # serve(), setup(), ok(), more(), login()
os.makedirs('tests/shots', exist_ok=True)
fails = []
def check(name, cond, extra=''):
    print(('PASS ' if cond else 'FAIL ') + name + (f'  [{extra}]' if extra else ''))
    if not cond: fails.append(name)

def page(b, w=390, h=844, init=''):
    pg = b.new_context(viewport={'width': w, 'height': h}).new_page()
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: (m.type == 'error' or 'Content Security Policy' in m.text) and errs.append(m.text))
    if init: pg.add_init_script(init)
    setup(pg); pg.goto('http://app.test/'); pg.wait_for_timeout(600)
    return pg, errs

with sync_playwright() as p:
    b = p.chromium.launch()
    # ---------- visitor ----------
    def mi(pg, label):
        more(pg, label)
    v, verr = page(b)
    bb = v.locator('#t-calc').bounding_box()
    check('phone: tab bar at the bottom', bb and bb['y'] > 844 - 90, str(bb))
    check('phone: 4 sections + ☰ Menu in the bar', v.is_visible('#t-menu') and not v.is_visible('#t-roadmap') and all(v.is_visible('#t-' + x) for x in ['calc', 'tools', 'interactions', 'sources']))
    check('no More panel, no side menu on phones', v.locator('#more, #more-btn').count() == 0 and not v.is_visible('#side'))
    v.click('#t-interactions'); v.wait_for_timeout(200)
    check('tab opens its page', v.evaluate('cur') == 'interactions')
    v.locator('#filters button').nth(1).click(); v.wait_for_timeout(200)
    check('interaction filter on the page', v.evaluate('IF') != 'all')
    v.evaluate("openToolSheet('tool-gz')"); v.wait_for_timeout(250)
    check('tool opens in floating window', v.is_visible('#sheet') and v.locator('#sheet-b #tool-gz').count() == 1)
    v.fill('#gw', '70'); v.dispatch_event('#gw', 'input'); v.wait_for_timeout(100)
    check('tool works inside window', 'ملغ' in v.inner_text('#gmg'))
    v.screenshot(path='tests/shots/tool_sheet.png')
    v.keyboard.press('Escape'); v.wait_for_timeout(150)
    check('Escape closes window and tool returns to its page', not v.is_visible('#sheet') and v.locator('#tools #tool-gz').count() == 1)
    v.click('#t-menu'); v.wait_for_timeout(300)
    check('☰ opens the Menu page', v.evaluate('cur') == 'menu' and v.is_visible('#menu') and v.get_attribute('#t-menu', 'aria-selected') == 'true')
    t = v.inner_text('#menu-b')
    check('Menu: account card, shortcuts, settings', all(x in t for x in ['الحساب', 'تسجيل الدخول', 'لديّ دعوة', 'اختصارات', 'القادم', 'سياسة الخصوصية', 'مشاركة التطبيق', 'الإعدادات', 'اللغة', 'المظهر', 'وضع العرض']), t[:200])
    check('Menu shortcuts are tiles', v.locator('#menu-b .mtile').count() >= 7)
    check('visitor: no management in Menu', 'الإدارة' not in t)
    v.screenshot(path='tests/shots/menu_ar.png', full_page=True)
    mi(v, 'سياسة الخصوصية')
    check('info page opens in window', v.is_visible('#sheet') and 'جهازك' in v.inner_text('#sheet-b'))
    check('visitor sees no edit in info page', v.locator('#sheet-b .sact').count() == 0)
    v.click('#sheet-x'); v.wait_for_timeout(100)
    mi(v, 'القادم')
    check('roadmap from Menu', v.evaluate('cur') == 'roadmap')
    ft = v.inner_text('footer')
    check('footer: only author and version', 'بواسطة سيف الدين' in ft and 'الإصدار' in ft and '@' not in ft and v.locator('footer a').count() == 0, ft)
    mi(v, 'English')
    check('language switch from Menu (stays on Menu)', v.evaluate('LANG') == 'en' and v.evaluate('cur') == 'menu')
    v.locator('#menu-b button', has_text='Dark').click(); v.wait_for_timeout(150)
    check('dark mode from Menu', v.evaluate("document.documentElement.dataset.theme") == 'dark')
    txt = v.inner_text('#menu') + v.inner_text('.tabs')
    check('English Menu and tab bar have no Arabic', not any('؀' <= c <= 'ۿ' for c in txt.replace('العربية', '')), txt[:120])
    v.screenshot(path='tests/shots/menu_en_dark.png', full_page=True)
    v.click('#t-calc'); v.wait_for_timeout(150)
    v.set_viewport_size({'width': 1366, 'height': 900}); v.wait_for_timeout(300)
    check('wide screen: side menu shown, tab bar hidden', v.is_visible('#side') and not v.is_visible('.tabs') and v.locator('#side-b .secs .mi').count() == 5)
    v.locator('#side-b .secs .mi', has_text='Sources').click(); v.wait_for_timeout(200)
    check('side menu sections switch pages', v.evaluate('cur') == 'sources' and v.locator('#side-b .secs .mi.on', has_text='Sources').count() == 1)
    v.evaluate("go('menu')"); v.wait_for_timeout(200)
    check('wide screen: Menu page falls back to the calculator', v.evaluate('cur') == 'calc')
    v.screenshot(path='tests/shots/desktop_en_dark.png')
    check('visitor errors', not verr, str(verr[:3]))

    # ---------- owner ----------
    o, oerr = page(b)
    login(o)
    o.click('#t-menu'); o.wait_for_timeout(250)
    t = o.inner_text('#menu-b')
    check('owner Menu: account card with publishing + management groups', all(x in t for x in ['معاينة', 'حفظ المسودة', 'نشر', 'الإدارة', 'بانتظار المراجعة', 'صفحات المعلومات', 'الصيادلة', 'التواصل والألوان', 'حسابي', 'خروج']), t[:300])
    check('review chips with counts', o.locator('#menu-b .mchips button .cn').count() >= 1)
    check('☰ shows a dot when something waits for review', o.is_visible('#nav-dot'))
    o.screenshot(path='tests/shots/owner_more.png')
    mi(o, 'صفحة جديدة')
    o.fill('#dlgf0', 'الأسئلة الشائعة'); o.fill('#dlgf1', 'FAQ'); o.fill('#dlgf2', 'سؤال أول\n\nجواب'); o.fill('#dlgf3', 'Question\n\nAnswer'); ok(o)
    check('new page shown in window after save', o.is_visible('#sheet') and o.inner_text('#sheet-t') == 'الأسئلة الشائعة')
    check('owner sees edit in page window', o.locator('#sheet-b .sact button').count() == 1)
    o.click('#sheet-x')
    check('new page in the Menu', o.locator(menu(o) + ' .mtile', has_text='الأسئلة الشائعة').count() == 1)
    # team
    mi(o, 'دعوة صيدلي')
    o.screenshot(path='tests/shots/invite_dialog.png')
    o.fill('#dlgf0', 'د. أحمد'); o.fill('#dlgf1', 'Ahmed@Example.com'); o.uncheck('#dlgf2 input[value="2"]'); o.check('#dlgf2 input[value="3"]'); ok(o); o.wait_for_timeout(300)
    link = o.input_value('#dlgf0') if o.is_visible('#dlg') else ''
    check('invitation link created', link.endswith('#join=ahmed%40example.com'), link)
    o.screenshot(path='tests/shots/invite_link.png')
    o.click('#dlg-a .pri'); o.wait_for_timeout(150)
    inv = o.evaluate("window.__st.team.invites[0]")
    check('invite saved with chosen permissions', inv['perms'] == {'nut': True, 'inter': True, 'refs': False, 'text': True}, json.dumps(inv['perms']))
    # simulate the pharmacist having signed up, then manage permissions
    o.evaluate("""(()=>{const st=window.__st;st.team.invites=[];st.team.members.push({id:'u2',email:'ahmed@example.com',name:'د. أحمد',role:'editor',status:'active',perms:{nut:true,inter:true,refs:false,text:true},last:null,pending:2})})()""")
    mi(o, 'الحسابات'); o.wait_for_timeout(200)
    check('accounts window lists pharmacist', 'د. أحمد' in o.inner_text('#sheet-b') and '2 بانتظار مراجعتك' in o.inner_text('#sheet-b'))
    o.locator('#sheet-b .tmc .filters button', has_text='المصادر').click(); o.wait_for_timeout(400)
    m = o.evaluate("window.__st.team.members.find(x=>x.id==='u2')")
    check('permission toggled on', m['perms']['refs'] is True)
    o.locator('#sheet-b button', has_text='إيقاف').click(); o.wait_for_timeout(400)
    m = o.evaluate("window.__st.team.members.find(x=>x.id==='u2')")
    check('account suspended', m['status'] == 'suspended' and 'موقوف' in o.inner_text('#sheet-b'))
    o.screenshot(path='tests/shots/team_sheet.png')
    o.click('#sheet-x')
    mi(o, 'معاينة')
    check('preview hides management', 'الإدارة' not in o.inner_text('#menu-b'))
    o.click('#o-pvexit'); o.wait_for_timeout(200)
    check('owner errors', not oerr, str(oerr[:3]))

    # ---------- pharmacist ----------
    e, eerr = page(b, init="window.__ROLE='editor';window.__PERMS={inter:true,text:true};window.__NAME='د. أحمد'")
    login(e)
    e.click('#t-menu'); e.wait_for_timeout(200); mt = e.inner_text('#menu-b')
    check('pharmacist: pages yes, team/review/site no', 'صفحات المعلومات' in mt and 'الصيادلة' not in mt and 'بانتظار المراجعة' not in mt and 'التواصل والألوان' not in mt, mt[:200])
    check('pharmacist More: save mine, my permissions, no publish', 'حفظ مسودتي' in mt and 'صلاحياتي' in mt and 'نشر' not in mt.replace('النشر', ''), mt)
    check('pharmacist name shown', 'د. أحمد' in mt)
    mi(e, 'صلاحياتي')
    check('my permissions window', 'التداخلات: مفعّلة' in e.inner_text('#sheet-b') and 'المصادر: مطفأة' in e.inner_text('#sheet-b'))
    e.screenshot(path='tests/shots/pharm_perms.png')
    check('pharmacist errors', not eerr, str(eerr[:3]))
    s, serr = page(b, init="window.__ROLE='editor';window.__STATUS='suspended'")
    login(s)
    check('suspended pharmacist cannot enter', not s.evaluate("document.body.classList.contains('owner')") and 'موقوف' in s.inner_text('#toast'))

    # ---------- invitation link ----------
    j = b.new_context(viewport={'width': 390, 'height': 844}).new_page(); j.add_init_script("window.__NOSESSION=1"); setup(j)
    j.goto('http://app.test/#join=ahmed%40example.com'); j.wait_for_timeout(900)
    check('invitation link opens create-account with e-mail', j.is_visible('#dlg') and j.input_value('#dlgf0') == 'ahmed@example.com', j.inner_text('#dlg-t') if j.is_visible('#dlg') else '')
    j.screenshot(path='tests/shots/join.png')

    # ---------- pharmacist edits / deletions of approved content (1.6.1) ----------
    # (runs before the seed is set, so it edits the seed as it is assigned)
    seed_chg = """(()=>{let v;Object.defineProperty(window,'__SEED',{configurable:true,get:()=>v,set:s=>{v=s;const x=s.inter[1];x.pv={...JSON.parse(JSON.stringify(x)),rv:true};x.d={ar:'وصف عدّله صيدلي',en:'Edited by a pharmacist'};x.rv=false;
      const gone=s.inter.splice(2,1)[0];const r=s.refs.find(y=>y.id===29);s.refs=s.refs.filter(y=>y.id!==29);s.del={refs:[{...r,rv:true}],inter:[{...gone,rv:true}],nut:[]};}});})();"""
    for w, h, n in [(390, 844, 'phone'), (768, 1024, 'ipad'), (1366, 900, 'desktop')]:
        c, cerr = page(b, w, h, seed_chg); login(c)
        if n == 'phone':
            check('review menu counts edit + 2 deletions', c.evaluate('pendCounts().c') == 3 and c.evaluate('pendCounts().d') == 2, str(c.evaluate('pendCounts()')))
            more(c, 'معاينة')
            check('preview shows the approved version, not the edit', c.evaluate("INTER.some(x=>x[3][0]==='وصف عدّله صيدلي')") is False and c.evaluate("INTER.some(x=>x[2][0]===__st.del.inter[0].b.ar)"))
            check('preview still shows a proposed deletion', c.evaluate('!!REFS[29]'))
            c.click('#o-pvexit'); c.wait_for_timeout(300)
        c.locator(menu(c) + ' .mchips button', has_text='تعديلات وحذف').click(); c.wait_for_timeout(300)
        check(f'{n}: changes window lists 3 items', c.locator('#sheet-b .tmc').count() == 3)
        check(f'{n}: no horizontal scroll in changes window', c.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        c.screenshot(path=f'tests/shots/{n}_changes.png')
        if n == 'phone':
            c.locator('#sheet-b .tmc', has_text='تعديل').first.locator('button', has_text='رفض التعديل').click(); c.wait_for_timeout(400)
            check('reject edit brings the approved text back', c.evaluate("CFG.inter.some(x=>x.d.ar==='وصف عدّله صيدلي')") is False and c.evaluate("CFG.inter[1].rv") is True)
            c.locator('#sheet-b .tmc', has_text='حذف مقترح').first.locator('button', has_text='تأكيد الحذف').click(); c.wait_for_timeout(400)
            c.locator('#sheet-b .tmc', has_text='حذف مقترح').first.locator('button', has_text='استرجاع').click(); c.wait_for_timeout(400)
            check('confirm one deletion, restore the other', c.locator('#sheet-b .tmc').count() == 0 and c.evaluate('delCount()') == 0, c.evaluate("JSON.stringify(__calls.filter(x=>x[1]==='review_change'))"))
            check('restored item is back in the list', c.evaluate("CFG.refs.some(x=>x.id===29)||CFG.inter.length===__SEED.inter.length+1"))
        check(f'{n}: no page errors (changes)', not cerr, str(cerr))

    # ---------- sizes ----------
    for w, h, n in [(768, 1024, 'ipad'), (1024, 768, 'ipad_landscape'), (1366, 900, 'desktop')]:
        d, derr = page(b, w, h)
        d.screenshot(path=f'tests/shots/{n}_home.png')
        if w < 1024:
            check(f'{n}: tab bar at the bottom', d.locator('#t-calc').bounding_box()['y'] > h - 90)
            d.click('#t-menu'); d.wait_for_timeout(300); d.screenshot(path=f'tests/shots/{n}_menu.png'); d.click('#t-sources')
        else:
            check(f'{n}: side menu instead of tab bar', d.is_visible('#side') and not d.is_visible('.tabs'))
            d.locator('#side-b .secs .mi').nth(3).click()
        d.wait_for_timeout(200); d.screenshot(path=f'tests/shots/{n}_sources.png')
        check(f'{n}: no horizontal scroll', d.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    print('\n' + ('ALL PASSED' if not fails else f'{len(fails)} FAILED: {fails}'))
    sys.exit(1 if fails else 0)
